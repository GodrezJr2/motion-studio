// The playbook: everything learned from studied references in one place, so a new piece can mix them. Each
// refs/study/<slug>/study.md carries front matter (tags, palette, type, moves, techniques) filled while watching,
// and study.json carries what was measured (shots, rhythm, the music's tempo and how the cuts sit on it).
// `ms playbook` folds them into refs/PLAYBOOK.md: the studies side by side, every move with where it was seen and
// whether core/moves.js has it yet, every technique and principle. `ms playbook "<words>"` pulls what matches, the
// starting point for a new concept that mixes several references. Local only: refs/ holds third-party work.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import { STUDY } from "./study.mjs";
import { SHELF } from "./shelf.mjs";
import { musicOf } from "./beat.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PLAYBOOK = path.join(SHELF, "PLAYBOOK.md");

const list = v => (Array.isArray(v) ? v : v ? [v] : []).map(String).filter(Boolean);

// Bullets under a "## <heading>" of a study.md
function bullets(body, heading) {
  const m = body.match(new RegExp(`^## ${heading}[^\\n]*\\n([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, "m"));
  return m ? m[1].split("\n").map(l => l.match(/^\s*[-*]\s+(.+)/)?.[1]).filter(Boolean) : [];
}

export async function readStudies() {
  if (!fs.existsSync(STUDY)) return [];
  const slugs = fs.readdirSync(STUDY).filter(s => fs.existsSync(path.join(STUDY, s, "study.json")));
  return Promise.all(slugs.map(async slug => {
    const dir = path.join(STUDY, slug);
    const data = JSON.parse(fs.readFileSync(path.join(dir, "study.json"), "utf8"));
    // Studies from before ms beat: measure the music once and keep it
    if (data.music === undefined && data.audio) {
      data.music = await musicOf(path.join(dir, "source.mp4"), data.cuts).catch(() => null);
      fs.writeFileSync(path.join(dir, "study.json"), JSON.stringify(data));
    }
    const md = fs.existsSync(path.join(dir, "study.md")) ? fs.readFileSync(path.join(dir, "study.md"), "utf8").replace(/\r\n/g, "\n") : "";
    const fm = md.match(/^---\n([\s\S]*?)\n---\n?/);
    let meta = {};
    try { meta = fm ? YAML.parse(fm[1]) || {} : {}; } catch (e) { meta = { error: e.message }; }
    const body = fm ? md.slice(fm[0].length) : md;
    const avg = data.shots.reduce((a, [x, y]) => a + y - x, 0) / data.shots.length;
    return {
      slug, dir, title: meta.title || (body.match(/^# (.+)/m)?.[1] ?? slug).slice(0, 80), by: meta.by || data.uploader || "",
      url: data.url || data.src, duration: data.duration, format: data.format, shots: data.shots.length, avgShot: +avg.toFixed(2),
      cutsPerMin: +(60 * (data.shots.length - 1) / data.duration).toFixed(1), music: data.music || null,
      tags: list(meta.tags), palette: list(meta.palette), type: list(meta.type), moves: list(meta.moves),
      techniques: list(meta.techniques), good: bullets(body, "What makes it good"), filled: !!fm, error: meta.error,
    };
  }));
}

// Move names core/moves.js already has
export function builtMoves() {
  const src = fs.readFileSync(path.join(ROOT, "core", "moves.js"), "utf8");
  return new Set([...src.matchAll(/^    ([a-zA-Z0-9]+)\(/gm)].map(m => m[1]));
}

const cell = s => String(s ?? "").replace(/\|/g, "\\|");

export async function playbook() {
  const studies = await readStudies();
  const built = builtMoves();
  const moves = new Map();
  for (const s of studies) for (const m of s.moves) {
    const name = m.split(/[\s:(]/)[0];
    if (!moves.has(name)) moves.set(name, { name, seen: [], notes: [] });
    moves.get(name).seen.push(s.slug);
    if (m !== name) moves.get(name).notes.push(m.slice(name.length).replace(/^[\s:]+/, ""));
  }
  const tagCount = {};
  for (const s of studies) for (const t of s.tags) tagCount[t] = (tagCount[t] || 0) + 1;
  const music = s => s.music ? `${s.music.bpm} BPM, ${Math.round(100 * (s.music.onBeat ?? 0))}% cuts on beat${s.music.lead != null ? `, lead ${s.music.lead}s` : ""}` : "";

  const md = `# Playbook

What ${studies.length} studied references taught. Generated by \`ms playbook\` from refs/study/*/study.md (front
matter) and study.json (measured); edit those, not this file. Mix: pick moves and techniques from different rows,
keep one palette and one type system per piece.

## Studies

| study | by | length | format | shots | avg shot | cuts/min | music | tags |
|---|---|---|---|---|---|---|---|---|
${studies.map(s => `| [${cell(s.title)}](study/${s.slug}/study.md)${s.filled ? "" : " (notes not filled)"} | ${cell(s.by)} | ${s.duration}s | ${s.format} | ${s.shots} | ${s.avgShot}s | ${s.cutsPerMin} | ${music(s)} | ${s.tags.join(", ")} |`).join("\n")}

## Moves

| move | in core/moves.js | seen in | notes |
|---|---|---|---|
${[...moves.values()].sort((a, b) => b.seen.length - a.seen.length || a.name.localeCompare(b.name)).map(m =>
  `| ${m.name} | ${built.has(m.name) ? "yes" : "**not yet**"} | ${m.seen.join(", ")} | ${cell(m.notes.join("; "))} |`).join("\n")}

## Techniques

${studies.filter(s => s.techniques.length).map(s => `**${s.slug}**\n\n${s.techniques.map(t => `- ${t}`).join("\n")}`).join("\n\n")}

## What makes them good

${studies.filter(s => s.good.length).map(s => `**${s.slug}**\n\n${s.good.map(t => `- ${t}`).join("\n")}`).join("\n\n")}

## Palettes and type

${studies.filter(s => s.palette.length || s.type.length).map(s => `- ${s.slug}: ${s.palette.join(" ")}${s.type.length ? ` · ${s.type.join(", ")}` : ""}`).join("\n")}

## Tags

${Object.entries(tagCount).sort((a, b) => b[1] - a[1]).map(([t, n]) => `${t} (${n})`).join(", ")}
`;
  fs.writeFileSync(PLAYBOOK, md);
  return { file: PLAYBOOK, studies, moves: [...moves.values()].map(m => ({ ...m, built: built.has(m.name) })) };
}

// What the playbook knows about some words: studies, moves, techniques and principles that mention any of them
export async function lookup(words) {
  const terms = words.toLowerCase().split(/[\s,]+/).filter(w => w.length > 1);
  const hit = s => terms.some(t => s.toLowerCase().includes(t));
  const { studies, moves } = await playbook();
  return {
    studies: studies.filter(s => hit([s.title, s.by, ...s.tags, ...s.type, ...s.moves].join(" "))).map(s => s.slug),
    moves: moves.filter(m => hit([m.name, ...m.notes].join(" "))),
    techniques: studies.flatMap(s => s.techniques.filter(hit).map(t => ({ study: s.slug, t }))),
    good: studies.flatMap(s => s.good.filter(hit).map(t => ({ study: s.slug, t }))),
  };
}
